"""Generate candidate, bit-exact FP32 step traces for the three hand images.

Run from the project root:
    python -m software.examples.fp32_step_traces \
        --output-dir software/examples/fp32_hand_image
    python -m software.examples.fp32_step_traces \
        --output-dir software/examples/fp32_hand_image --check

The traces describe the software proposal, not accepted RTL behaviour. Only
expected_traces.json and expected_traces.sha256 are written in output-dir.
"""

from __future__ import annotations

import argparse
import hashlib
import json
from pathlib import Path

from software.examples.fp32_hand_example import (
    BIAS, EXPECTED, ROUNDING_BIAS, ROUNDING_EXPECTED, ROUNDING_W,
    ROUNDING_X, TILE_BIAS, TILE_EXPECTED, TILE_W, TILE_X, W, X,
)
from software.fp32_reference import run_ffn1_bits, trace_cell


TRACE_NAME = "expected_traces.json"
HASH_NAME = "expected_traces.sha256"


def _hex32(bits: int) -> str:
    return f"0x{bits:08x}"


def _case(name: str, x: list[list[int]], w: list[list[int]],
          bias: list[int], expected: list[list[int]]) -> dict:
    # These independently written output constants must still agree with the
    # candidate model before its internal steps are distributed to hardware.
    if run_ffn1_bits(x, w, bias) != expected:
        raise AssertionError(f"reference disagrees with hand case {name}")

    cells = []
    for row in range(len(x)):
        for column in range(len(bias)):
            raw = trace_cell(x, w, bias, row, column)
            if raw["result_bits"] != expected[row][column]:
                raise AssertionError(f"trace disagrees with hand case {name}")
            acc_before = 0
            steps = []
            for step in raw["steps"]:
                k = step["k"]
                steps.append({
                    "k": k,
                    "x_bits": _hex32(x[row][k]),
                    "w_bits": _hex32(w[k][column]),
                    "acc_before_bits": _hex32(acc_before),
                    "product_bits": _hex32(step["product_bits"]),
                    "acc_after_bits": _hex32(step["acc_bits"]),
                })
                acc_before = step["acc_bits"]
            cells.append({
                "row": row,
                "column": column,
                "initial_acc_bits": "0x00000000",
                "steps": steps,
                "acc_before_bias_bits": _hex32(acc_before),
                "bias_bits": _hex32(bias[column]),
                "result_bits": _hex32(raw["result_bits"]),
            })
    return {
        "x_shape": [len(x), len(x[0])],
        "w_shape": [len(w), len(w[0])],
        "y_shape": [len(x), len(bias)],
        "cells": cells,
    }


def render() -> tuple[bytes, bytes]:
    document = {
        "schema_version": 1,
        "status": "CANDIDATE software FP32 trace; hardware acceptance pending",
        "arithmetic": (
            "finite binary32; k ascending; independently round product and "
            "accumulator addition to nearest-even; no FMA; add bias once after "
            "all k; gradual underflow"
        ),
        "word_format": "each bit pattern is an eight-digit hexadecimal IEEE-754 binary32 word",
        "cases": {
            "hand_2x2": _case("hand_2x2", X, W, BIAS, EXPECTED),
            "rounding_nonfused": _case(
                "rounding_nonfused", ROUNDING_X, ROUNDING_W,
                ROUNDING_BIAS, ROUNDING_EXPECTED),
            "k32_boundary": _case(
                "k32_boundary", TILE_X, TILE_W, TILE_BIAS,
                TILE_EXPECTED),
        },
    }
    payload = (json.dumps(document, indent=2, ensure_ascii=False) + "\n").encode("utf-8")
    digest = hashlib.sha256(payload).hexdigest()
    checksum = f"{digest}  {TRACE_NAME}\n".encode("ascii")
    return payload, checksum


def generate(output_dir: Path, *, check: bool = False) -> tuple[Path, Path]:
    payload, checksum = render()
    trace_path = output_dir / TRACE_NAME
    checksum_path = output_dir / HASH_NAME
    if check:
        if trace_path.read_bytes() != payload or checksum_path.read_bytes() != checksum:
            raise ValueError("checked-in FP32 traces differ from regenerated bytes")
    else:
        output_dir.mkdir(parents=True, exist_ok=True)
        trace_path.write_bytes(payload)
        checksum_path.write_bytes(checksum)
    return trace_path, checksum_path


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output-dir", required=True, type=Path)
    parser.add_argument("--check", action="store_true",
                        help="compare regenerated bytes without writing files")
    args = parser.parse_args()
    trace_path, checksum_path = generate(args.output_dir, check=args.check)
    print(f"{trace_path}\n{checksum_path}")


if __name__ == "__main__":
    main()
