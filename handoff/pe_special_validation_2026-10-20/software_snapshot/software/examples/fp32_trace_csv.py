"""Render a SOFTWARE-ONLY demonstration of the proposed PE trace CSV.

This reformats the existing candidate FP32 step traces. It is not sampled
from RTL, and its blank cycle/RTL fields must never be treated as hardware
evidence. Use --check to verify the checked-in demonstration is reproducible.
"""

from __future__ import annotations

import argparse
import csv
from hashlib import sha256
import io
import json
from pathlib import Path

from software.examples.fp32_step_traces import render as render_steps


HEADER = (
    "source_kind", "case_id", "tile_id", "row", "column", "event",
    "cycle", "valid", "k", "x_bits", "w_bits", "acc_before_bits",
    "product_bits", "acc_after_bits", "bias_bits", "result_bits",
    "rtl_commit", "input_manifest_sha256", "reference_trace_sha256",
)
NAME = "expected_pe_trace_demo.csv"
HASH_NAME = "expected_pe_trace_demo.sha256"


def render() -> tuple[bytes, bytes]:
    trace_bytes, _ = render_steps()
    document = json.loads(trace_bytes)
    trace_digest = sha256(trace_bytes).hexdigest()
    manifest_digest = sha256((Path(__file__).with_name("fp32_hand_image") /
                              "manifest.json").read_bytes()).hexdigest()
    output = io.StringIO(newline="")
    writer = csv.DictWriter(output, fieldnames=HEADER, lineterminator="\n")
    writer.writeheader()
    for case_id, case in document["cases"].items():
        for cell in case["cells"]:
            common = {
                "source_kind": "software_candidate",
                "case_id": case_id,
                "row": cell["row"],
                "column": cell["column"],
                "cycle": "",
                "valid": 1,
                "rtl_commit": "",
                "input_manifest_sha256": manifest_digest,
                "reference_trace_sha256": trace_digest,
            }
            for step in cell["steps"]:
                writer.writerow({
                    **common,
                    "tile_id": step["k"] // 32 if case_id == "k32_boundary" else 0,
                    "event": "mac",
                    "k": step["k"],
                    "x_bits": step["x_bits"],
                    "w_bits": step["w_bits"],
                    "acc_before_bits": step["acc_before_bits"],
                    "product_bits": step["product_bits"],
                    "acc_after_bits": step["acc_after_bits"],
                })
            last_k = cell["steps"][-1]["k"]
            writer.writerow({
                **common,
                "tile_id": last_k // 32 if case_id == "k32_boundary" else 0,
                "event": "bias",
                "acc_before_bits": cell["acc_before_bias_bits"],
                "acc_after_bits": cell["result_bits"],
                "bias_bits": cell["bias_bits"],
                "result_bits": cell["result_bits"],
            })
    payload = output.getvalue().encode("ascii")
    checksum = f"{sha256(payload).hexdigest()}  {NAME}\n".encode("ascii")
    return payload, checksum


def write(output_dir: Path, *, check: bool = False) -> tuple[Path, Path]:
    payload, checksum = render()
    csv_path = output_dir / NAME
    hash_path = output_dir / HASH_NAME
    if check:
        if csv_path.read_bytes() != payload or hash_path.read_bytes() != checksum:
            raise ValueError("checked-in software PE trace demo differs from regenerated bytes")
    else:
        output_dir.mkdir(parents=True, exist_ok=True)
        csv_path.write_bytes(payload)
        hash_path.write_bytes(checksum)
    return csv_path, hash_path


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output-dir", required=True, type=Path)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    csv_path, hash_path = write(args.output_dir, check=args.check)
    print(f"{csv_path}\n{hash_path}")


if __name__ == "__main__":
    main()
